"""Generate the Python log module and the data dictionary from schema/fields.yaml.

    python -m schema.gen_py           write analysis/logread/slog_v<N>.py and docs/data_dictionary.md
    python -m schema.gen_py --check   exit 1 if either is stale (CI)
    python -m schema.gen_py --freeze  copy fields.yaml to schema/versions/fields_v<N>.yaml

The generated module uses the standard library only, so the tools that talk to the arm can
write logs with it (codebase plan §2, §5). The generator itself uses PyYAML.
"""
import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
FIELDS = ROOT / "schema" / "fields.yaml"
VERSIONS = ROOT / "schema" / "versions"
DOCS = ROOT / "docs" / "data_dictionary.md"
STRUCT = {"u8": "B", "u16": "H", "u32": "I", "u64": "Q", "i32": "i", "i64": "q", "f64": "d"}


def load_schema(path=FIELDS):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _field_layout(f):
    t = f["type"]
    if t == "bytes":
        return None, None
    if "[" in t:
        base, n = t[:-1].split("[")
        return STRUCT[base] * 1, int(n)
    return STRUCT[t], 1


def validate(schema):
    tags, names = set(), set()
    for s in schema["streams"]:
        if s["tag"] in tags or s["name"] in names:
            raise ValueError(f"duplicate stream tag or name: {s['name']}")
        tags.add(s["tag"])
        names.add(s["name"])
        if s["file"] not in schema["files"]:
            raise ValueError(f"{s['name']}: unknown file {s['file']}")
        fnames = [f["name"] for f in s["fields"]]
        if len(set(fnames)) != len(fnames):
            raise ValueError(f"{s['name']}: duplicate field")
        for i, f in enumerate(s["fields"]):
            if f["type"] == "bytes" and i != len(s["fields"]) - 1:
                raise ValueError(f"{s['name']}.{f['name']}: a bytes field must be last")
            if f["type"] != "bytes":
                _field_layout(f)
            if "unit" not in f:
                raise ValueError(f"{s['name']}.{f['name']}: unit missing (F1)")


def gen_module(schema):
    v = schema["schema_version"]
    lines = [
        f"# GENERATED by schema/gen_py.py from schema/fields.yaml (schema_version {v}). Do not edit.",
        f'"""Log writer and reader, schema version {v} (codebase plan §5). Standard library only."""',
        "import json",
        "import struct",
        "import threading",
        "",
        f"SCHEMA_VERSION = {v}",
        "MAGIC = {" + ", ".join(f'"{k}": b"{f["magic"]}"' for k, f in schema["files"].items()) + "}",
        '_REC = struct.Struct("<HI")      # tag, payload length',
        '_HDR = struct.Struct("<I")       # header JSON length',
        "",
        "",
        "class Stream:",
        '    __slots__ = ("name", "tag", "file", "fixed", "fields", "var")',
        "",
        "    def __init__(self, name, tag, file, fmt, fields, var):",
        "        self.name, self.tag, self.file, self.fields, self.var = name, tag, file, fields, var",
        "        self.fixed = struct.Struct(fmt)",
        "",
        "",
        "STREAMS = {",
    ]
    for s in schema["streams"]:
        fmt, flds, var = "<", [], None
        for f in s["fields"]:
            code, n = _field_layout(f)
            if code is None:
                var = f["name"]
                continue
            fmt += (str(n) if n > 1 else "") + code
            flds.append((f["name"], n))
        lines.append(f'    "{s["name"]}": Stream("{s["name"]}", {s["tag"]}, "{s["file"]}", "{fmt}", {tuple(flds)!r}, {var!r}),')
    lines += [
        "}",
        "TAGS = {s.tag: s for s in STREAMS.values()}",
        "",
        "",
        "def pack(stream, fields):",
        '    """dict of field values -> payload bytes. Every field is required; no extras."""',
        "    s = STREAMS[stream]",
        "    expected = {n for n, _ in s.fields} | ({s.var} if s.var else set())",
        "    if set(fields) != expected:",
        '        raise ValueError(f"{stream}: fields {sorted(set(fields) ^ expected)} missing or unexpected")',
        "    vals = []",
        "    for name, n in s.fields:",
        "        x = fields[name]",
        "        if n == 1:",
        "            vals.append(x)",
        "        else:",
        "            if len(x) != n:",
        '                raise ValueError(f"{stream}.{name}: {n} values expected, got {len(x)}")',
        "            vals.extend(x)",
        "    payload = s.fixed.pack(*vals)",
        "    if s.var:",
        "        data = fields[s.var]",
        "        if not isinstance(data, (bytes, bytearray)):",
        '            raise TypeError(f"{stream}.{s.var}: bytes expected")',
        "        payload += bytes(data)",
        "    return payload",
        "",
        "",
        "def unpack(stream, payload):",
        '    """payload bytes -> dict. A longer fixed payload (fields appended by a later version) is accepted."""',
        "    s = STREAMS[stream]",
        "    vals = s.fixed.unpack_from(payload)",
        "    out, i = {}, 0",
        "    for name, n in s.fields:",
        "        out[name] = vals[i] if n == 1 else list(vals[i:i + n])",
        "        i += n",
        "    if s.var:",
        "        out[s.var] = bytes(payload[s.fixed.size:])",
        "    return out",
        "",
        "",
        "class Writer:",
        '    """Append-only. Opens with "xb": an existing file is never overwritten (A4)."""',
        "",
        '    def __init__(self, path, header, file="bin", flush_each=True):',
        "        self.file_kind = file",
        "        self.flush_each = flush_each",
        "        self.lock = threading.Lock()",
        "        self.records = 0",
        '        self.f = open(path, "xb")',
        '        hdr = dict(header, schema_version=SCHEMA_VERSION, file=file)',
        '        blob = json.dumps(hdr, sort_keys=True, ensure_ascii=False).encode("utf-8")   # D5: sorted keys',
        "        self.f.write(MAGIC[file] + _HDR.pack(len(blob)) + blob)",
        "        self.f.flush()",
        "",
        "    def write(self, stream, **fields):",
        "        s = STREAMS[stream]",
        "        if s.file != self.file_kind:",
        '            raise ValueError(f"{stream} belongs in the .{s.file} file")',
        "        payload = pack(stream, fields)",
        "        with self.lock:",
        "            self.f.write(_REC.pack(s.tag, len(payload)) + payload)",
        "            self.records += 1",
        "            if self.flush_each:",
        "                self.f.flush()",
        "",
        "    def flush(self):",
        "        with self.lock:",
        "            self.f.flush()",
        "",
        "    def close(self):",
        "        with self.lock:",
        "            if not self.f.closed:",
        "                self.f.flush()",
        "                self.f.close()",
        "",
        "    def __enter__(self):",
        "        return self",
        "",
        "    def __exit__(self, *exc):",
        "        self.close()",
        "",
        "",
        "class Trial:",
        '    def __init__(self, header, records, truncated, unknown_tags):',
        "        self.header, self.records, self.truncated, self.unknown_tags = header, records, truncated, unknown_tags",
        "",
        "    def stream(self, name):",
        "        return [r for s, r in self.records if s == name]",
        "",
        "",
        "def read_bytes(blob):",
        '    """Parse a whole file. A truncated last record ends the trial (truncated=True), never an error;',
        '    tags this version does not know are skipped and counted."""',
        "    kind = next((k for k, m in MAGIC.items() if blob[:len(m)] == m), None)",
        "    if kind is None:",
        '        raise ValueError("not a slosh log file")',
        "    pos = len(MAGIC[kind])",
        "    (n,) = _HDR.unpack_from(blob, pos)",
        "    pos += _HDR.size",
        "    if pos + n > len(blob):",
        '        raise ValueError("header truncated")',
        '    header = json.loads(blob[pos:pos + n].decode("utf-8"))',
        "    pos += n",
        "    records, truncated, unknown = [], False, 0",
        "    while pos < len(blob):",
        "        if pos + _REC.size > len(blob):",
        "            truncated = True",
        "            break",
        "        tag, length = _REC.unpack_from(blob, pos)",
        "        start = pos + _REC.size",
        "        if start + length > len(blob):",
        "            truncated = True",
        "            break",
        "        s = TAGS.get(tag)",
        "        if s is None:",
        "            unknown += 1",
        "        else:",
        "            records.append((s.name, unpack(s.name, blob[start:start + length])))",
        "        pos = start + length",
        "    return Trial(header, records, truncated, unknown)",
        "",
        "",
        "def read(path):",
        '    with open(path, "rb") as f:',
        "        return read_bytes(f.read())",
        "",
    ]
    return "\n".join(lines)


def gen_docs(schema):
    v = schema["schema_version"]
    out = [f"# Data dictionary, log schema version {v}", "",
           "Generated from `schema/fields.yaml` by `schema/gen_py.py`. Do not edit.", "",
           "Every record is a tag (u16), a payload length (u32) and the payload, little-endian. "
           "A file starts with its magic, a u32 header length and the header as JSON. "
           "A truncated last record is the end of the trial.", ""]
    for s in schema["streams"]:
        out += [f"## `{s['name']}` (tag {s['tag']}, `.{s['file']}`, since v{s['since_version']})", "",
                s.get("doc", ""), "", "| Field | Type | Unit | Frame | Notes |", "|---|---|---|---|---|"]
        for f in s["fields"]:
            out.append(f"| `{f['name']}` | {f['type']} | {f['unit']} | {f.get('frame', '')} | {f.get('doc', '')} |")
        out.append("")
    return "\n".join(out)


def outputs(schema):
    return {ROOT / "analysis" / "logread" / f"slog_v{schema['schema_version']}.py": gen_module(schema) + "\n",
            DOCS: gen_docs(schema) + "\n"}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--freeze", action="store_true")
    a = ap.parse_args(argv)
    schema = load_schema()
    validate(schema)
    frozen = VERSIONS / f"fields_v{schema['schema_version']}.yaml"
    current = FIELDS.read_text(encoding="utf-8")
    if frozen.exists() and frozen.read_text(encoding="utf-8") != current:
        sys.exit(f"schema_version {schema['schema_version']} is frozen ({frozen.name}) but fields.yaml differs: bump it")
    stale = []
    for path, text in outputs(schema).items():
        if a.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        sys.exit("stale generated files: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
    if a.freeze:
        VERSIONS.mkdir(exist_ok=True)
        if frozen.exists():
            sys.exit(f"{frozen.name} already exists")
        frozen.write_text(current, encoding="utf-8", newline="\n")
        print(f"froze {frozen.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
