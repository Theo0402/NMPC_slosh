"""Read any trial file, whatever its schema version (codebase plan §5: version-N readers stay
in the tree forever). The per-version modules are generated by schema/gen_py.py.
Standard library only."""
import importlib
import json
import struct


def read_trial(path):
    with open(path, "rb") as f:
        blob = f.read()
    (n,) = struct.unpack_from("<I", blob, 8)
    version = json.loads(blob[12:12 + n].decode("utf-8"))["schema_version"]
    module = importlib.import_module(f"analysis.logread.slog_v{int(version)}")
    return module.read_bytes(blob)


def latest():
    """The module for the newest schema version: the one writers use."""
    from analysis.logread import slog_v1
    return slog_v1
